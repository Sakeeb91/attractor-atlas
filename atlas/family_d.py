"""The dihedral D_n-equivariant search family, evaluated in batches.

This is the first DIHEDRAL member of the program. The C_n family
(atlas/family.py) is equivariant under rotations about z alone; this family
adds a half-turn about a horizontal axis, giving the chiral dihedral group
D_n of order 2n (Schoenflies), generated by

    rho_n: (w, z) -> (e^{2 pi i/n} w, z)     rotation about z by 2 pi/n
    kappa: (w, z) -> (conj(w), -z)            half-turn about the x axis,
                                              i.e. (x, y, z) -> (x, -y, -z)

with w = x + i*y. All 2n elements are proper rotations (det +1): n rotations
about z and n half-turns about in-plane axes at angles k*pi/n. The group is
chiral, so the attractor has no mirror symmetry of any kind.

Equivariance conditions for dw/dt = f, dz/dt = h (both maps are linear):

    rho_n:  f(e w, z) = e f(w, z),           h(e w, z) = h(w, z),   e = e^{2 pi i/n}
    kappa:  f(conj w, -z) = conj f(w, z),    h(conj w, -z) = -h(w, z)

The candidate family (8 dials, all audited in tests/test_d_equivariance.py):

    dw/dt = (alpha*z^2 - beta + i*omega*z) w
            + gamma*conj(w)^(n-1) + i*delta*z*conj(w)^(n-1)
    dz/dt = nu*z - z^3 - lam*z*|w|^2 + eps*Im(w^n)

Term audit:

    term                       rho_n   kappa   sigma_h  sigma_v  S_2n/sigma_d  C_2n
    (alpha z^2 - beta) w        ok      ok      ok       ok       ok            ok
    i omega z w                 ok      ok      BREAKS   BREAKS   BREAKS        ok
    gamma conj(w)^(n-1)         ok      ok      ok       ok       BREAKS        BREAKS
    i delta z conj(w)^(n-1)     ok      ok      BREAKS   BREAKS   ok            BREAKS
    nu z - z^3 - lam z |w|^2    ok      ok      ok       ok       ok            ok
    eps Im(w^n)                 ok      ok      BREAKS   BREAKS   ok            BREAKS

where sigma_h is the z-flip (w, z) -> (w, -z), sigma_v the vertical mirror
(w, z) -> (conj w, z) through a half-turn axis, S_2n the rotoreflection
(w, z) -> (e^{i pi/n} w, -z), sigma_d the diagonal mirror
(w, z) -> (e^{i pi/n} conj w, z), and C_2n the rotation by pi/n. Hence:

  * kappa forbids uniform spin. A constant rate i*omega0*w is not
    kappa-equivariant; the only allowed rotation rate is ODD in z, so the
    flow turns one way above the mid-plane and the other way below it, and
    kappa exchanges the two halves (a counter-rotating vortex pair).
  * omega = delta = eps = 0 collapses the family to D_nh (sigma_h, sigma_v
    become symmetries). The terms i*omega*z*w, i*delta*z*conj(w)^(n-1) and
    eps*Im(w^n) are the D_n-not-D_nh signatures.
  * omega = gamma = 0 collapses the family to D_nd (S_2n, sigma_d).
  * gamma = delta = eps = 0 restores rotation by every angle.
  Generic parameters therefore carry exactly D_n among the axial point groups
  that contain it (D_nh, D_nd, D_2n and their supergroups). The polyhedral
  rotation groups that contain D_n (T, O and I for n = 2; O and I for n = 3;
  O for n = 4; I for n = 5) add rotation axes off z. polyhedral_overgroups(n)
  builds every embedding of them that contains this D_n, and the tests check
  that every one of their extra elements is broken.

Real form for n = 3 (c = alpha*z^2 - beta):

    dx/dt = c x - omega z y + gamma (x^2 - y^2) + 2 delta z x y
    dy/dt = c y + omega z x - 2 gamma x y + delta z (x^2 - y^2)
    dz/dt = nu z - z^3 - lam z (x^2 + y^2) + eps (3 x^2 y - y^3)

Divergence (any n): the omega, gamma and delta terms are trace-free (the
first is a z-dependent rotation, the other two are anti-holomorphic in w), and
Im(w^n) does not depend on z, so

    div F = 2 (alpha z^2 - beta) + nu - 3 z^2 - lam (x^2 + y^2).

Equilibrium skeleton (any n >= 3):
  * The on-axis triple z (nu - z^2) = 0: the origin and (0, 0, +-sqrt(nu)).
  * At z = 0 the planar linear part is -beta * Identity (the rotation rate
    omega*z vanishes there), so the origin has a DOUBLE real eigenvalue
    -beta plus nu along z: a saddle, not a saddle-focus (unlike the C_n
    specimens, whose rotation rate is a constant).
  * The pair (0, 0, +-sqrt(nu)) is exchanged by kappa: identical spectra,
    opposite rotation sense (the sign of J_xy - J_yx flips).
  * Equilibria in the plane z = 0 lie on the half-turn axes and form orbits
    of size n; generic off-axis equilibria form orbits of size 2n.
  The only point fixed by all of D_n is the origin, so a D_n-invariant
  attractor must be centred on it.

The evaluator mirrors atlas/family.py: vectorized complex RK4 over a whole
batch, a two-orbit Benettin estimate of the largest Lyapunov exponent, and a
decimated orbit sample for fingerprinting. The two-orbit estimate is a search
signal only; certification needs the fine-dt tangent QR integrator
(docs/METHODOLOGY.md section 9).
"""

from __future__ import annotations

import numpy as np

# Parameter order: (alpha, beta, omega, gamma, delta, nu, lam, eps)
_PARAM_NAMES = ("alpha", "beta", "omega", "gamma", "delta", "nu", "lam", "eps")
PARAM_LO = np.array([0.3, -1.0, 0.5, 0.2, -2.0, 0.3, 0.5, -2.5])
PARAM_HI = np.array([2.5, 1.5, 4.0, 2.5, 2.0, 3.0, 3.0, 2.5])
N_PARAMS = 8

ESCAPE = 50.0


def param_names():
    """Names of the eight parameters, in the order PARAM_LO/PARAM_HI use."""
    return list(_PARAM_NAMES)


def rho(w, z, n):
    """The rotation generator rho_n: (w, z) -> (e^{2 pi i/n} w, z)."""
    return np.exp(2j * np.pi / n) * w, z


def kappa(w, z):
    """The half-turn generator about the x axis: (w, z) -> (conj(w), -z)."""
    return np.conj(w), -z


def group_matrices(n):
    """The 2n elements of D_n as real 3x3 matrices acting on (x, y, z).

    Built as the closure of rho_n and kappa = diag(1, -1, -1) under matrix
    multiplication. Order: identity first, then breadth-first discovery.
    """
    c, s = np.cos(2 * np.pi / n), np.sin(2 * np.pi / n)
    gens = [
        np.array([[c, -s, 0.0], [s, c, 0.0], [0.0, 0.0, 1.0]]),
        np.diag([1.0, -1.0, -1.0]),
    ]
    elems = [np.eye(3)]
    frontier = [np.eye(3)]
    while frontier:
        nxt = []
        for a in frontier:
            for g in gens:
                m = g @ a
                if not any(np.allclose(m, e, atol=1e-9) for e in elems):
                    elems.append(m)
                    nxt.append(m)
        frontier = nxt
    return elems


def _closure(gens):
    elems = [np.eye(3)]
    frontier = [np.eye(3)]
    while frontier:
        nxt = []
        for a in frontier:
            for g in gens:
                m = g @ a
                if not any(np.allclose(m, e, atol=1e-9) for e in elems):
                    elems.append(m)
                    nxt.append(m)
        frontier = nxt
    return elems


def _axis_rotation(axis, angle):
    a = np.asarray(axis, dtype=float)
    a = a / np.linalg.norm(a)
    K = np.array([[0.0, -a[2], a[1]], [a[2], 0.0, -a[0]], [-a[1], a[0], 0.0]])
    return np.eye(3) + np.sin(angle) * K + (1 - np.cos(angle)) * (K @ K)


def _axis_and_angle(m):
    ang = float(np.arccos(np.clip((np.trace(m) - 1.0) / 2.0, -1.0, 1.0)))
    vals, vecs = np.linalg.eig(m)
    ax = np.real(vecs[:, np.argmin(np.abs(vals - 1.0))])
    return ax / np.linalg.norm(ax), ang


def _polyhedral_standard():
    """T, O and I as rotation-matrix lists in a standard orientation."""
    phi = (1 + 5 ** 0.5) / 2
    T = _closure([_axis_rotation((1, 1, 1), 2 * np.pi / 3), _axis_rotation((0, 0, 1), np.pi)])
    O = _closure([_axis_rotation((1, 1, 1), 2 * np.pi / 3), _axis_rotation((0, 0, 1), np.pi / 2)])
    I = _closure([_axis_rotation((1, 1, 1), 2 * np.pi / 3), _axis_rotation((0, 1, phi), 2 * np.pi / 5)])
    assert (len(T), len(O), len(I)) == (12, 24, 60)
    return {"T": T, "O": O, "I": I}


def polyhedral_overgroups(n):
    """Every polyhedral rotation group (T, O, I) that contains this D_n.

    D_n here has its n-fold axis along z and a half-turn about x. A polyhedral
    group P contains a conjugate of D_n when it has an n-fold axis a (for
    n = 2, a 2-fold axis) and a 2-fold axis b perpendicular to it; rotating a
    onto z and b onto x gives a copy of P that contains exactly this D_n.
    All such copies are returned, deduplicated, as a list of
    (name, matrices) pairs. Only n in {2, 3, 4, 5} have any.
    """
    Dn = group_matrices(n)
    out, seen = [], []
    for name, P in _polyhedral_standard().items():
        axes = [_axis_and_angle(m) for m in P[1:]]
        n_axes = [a for a, t in axes if abs(t - 2 * np.pi / n) < 1e-9]
        two = [a for a, t in axes if abs(t - np.pi) < 1e-9]
        for a in n_axes:
            for b in two:
                if abs(a @ b) > 1e-9:
                    continue
                R = np.array([b, np.cross(a, b), a])  # rows: new x, y, z
                G = [R @ m @ R.T for m in P]
                if not all(any(np.allclose(d, g, atol=1e-9) for g in G) for d in Dn):
                    continue
                key = sorted(tuple(np.round(g, 6).ravel()) for g in G)
                if key in seen:
                    continue
                seen.append(key)
                out.append((name, G))
    return out


def velocity(w, z, p, n):
    """Right-hand side (dw/dt, dz/dt) at a single state (w complex, z real).

    ``p`` is a length-8 array-like in the order given by ``param_names()``.
    """
    al, be, om, ga, de, nu, lam, eps = (float(v) for v in p)
    wb = np.conj(w) ** (n - 1)
    dw = (al * z * z - be + 1j * om * z) * w + (ga + 1j * de * z) * wb
    mod2 = (w * np.conj(w)).real
    dz = nu * z - z**3 - lam * z * mod2 + eps * (w**n).imag
    return dw, dz


def _deriv(W, Z, p, n):
    al, be, om, ga, de, nu, lam, eps = p.T
    Wb = np.conj(W) ** (n - 1)
    dW = (al * Z * Z - be + 1j * om * Z) * W + (ga + 1j * de * Z) * Wb
    mod2 = W.real**2 + W.imag**2
    dZ = nu * Z - Z**3 - lam * Z * mod2 + eps * (W**n).imag
    return dW, dZ


def _rk4(W, Z, p, n, dt):
    k1w, k1z = _deriv(W, Z, p, n)
    k2w, k2z = _deriv(W + 0.5 * dt * k1w, Z + 0.5 * dt * k1z, p, n)
    k3w, k3z = _deriv(W + 0.5 * dt * k2w, Z + 0.5 * dt * k2z, p, n)
    k4w, k4z = _deriv(W + dt * k3w, Z + dt * k3z, p, n)
    return (
        W + dt / 6.0 * (k1w + 2 * k2w + 2 * k3w + k4w),
        Z + dt / 6.0 * (k1z + 2 * k2z + 2 * k3z + k4z),
    )


def evaluate_batch(
    params,
    n,
    dt=0.01,
    transient=8_000,
    lyap_steps=25_000,
    sample_steps=12_000,
    sample_every=8,
    seed=0,
):
    """Evaluate a (B, 8) batch of D_n parameter vectors.

    Returns dict with:
      lle     (B,) largest Lyapunov exponent (nan where dead)
      alive   (B,) bool: bounded and finite throughout
      points  (B, sample_steps // sample_every, 3) orbit samples (nan where dead)
    """
    p = np.asarray(params, dtype=float)
    B = p.shape[0]
    rng = np.random.default_rng(seed)

    # Start off the z axis and off the half-turn axes: both are invariant
    # lines (fixed sets of rho_n and of the half-turns) and would trap the orbit.
    W = (rng.uniform(-0.4, 0.4, B) + 1j * rng.uniform(-0.4, 0.4, B)) + (0.3 + 0.2j)
    Z = rng.uniform(-0.2, 0.4, B)
    alive = np.ones(B, dtype=bool)

    def cull():
        nonlocal alive
        bad = ~np.isfinite(Z) | (np.abs(Z) > ESCAPE) | ~np.isfinite(W) | (np.abs(W) > ESCAPE)
        alive &= ~bad
        W[bad] = 0.0
        Z[bad] = 0.0

    with np.errstate(all="ignore"):
        for i in range(transient):
            W, Z = _rk4(W, Z, p, n, dt)
            if i % 200 == 0:
                cull()
        cull()

        d0 = 1e-8
        Ws, Zs = W + d0, Z.copy()
        log_sum = np.zeros(B)
        for i in range(lyap_steps):
            W, Z = _rk4(W, Z, p, n, dt)
            Ws, Zs = _rk4(Ws, Zs, p, n, dt)
            dW = Ws - W
            dZ = Zs - Z
            d = np.sqrt(dW.real**2 + dW.imag**2 + dZ**2)
            d = np.where(d > 0, d, 1e-16)
            log_sum += np.log(d / d0)
            scale = d0 / d
            Ws = W + dW * scale
            Zs = Z + dZ * scale
            if i % 200 == 0:
                cull()
        cull()
        lle = np.where(alive, log_sum / (lyap_steps * dt), np.nan)

        n_keep = sample_steps // sample_every
        pts = np.full((B, n_keep, 3), np.nan)
        k = 0
        for i in range(sample_steps):
            W, Z = _rk4(W, Z, p, n, dt)
            if i % sample_every == 0:
                pts[:, k, 0] = W.real
                pts[:, k, 1] = W.imag
                pts[:, k, 2] = Z
                k += 1
            if i % 200 == 0:
                cull()
        cull()
        pts[~alive] = np.nan

    return {"lle": lle, "alive": alive, "points": pts}


def sample_params(B, rng):
    """Uniform random parameter vectors inside the search box."""
    return rng.uniform(PARAM_LO, PARAM_HI, size=(B, N_PARAMS))


def mutate_params(parent, rng, sigma_frac=0.08):
    """Gaussian mutation, clipped to the box; sigma_frac is a fraction of each range."""
    span = PARAM_HI - PARAM_LO
    child = parent + rng.normal(0, sigma_frac, size=parent.shape) * span
    return np.clip(child, PARAM_LO, PARAM_HI)
