"""Core definition of the Trinacria attractor.

Trinacria is the first DIHEDRAL member of the program. Naiad (C2), Aurelia
(C3) and Cassiopea (C4) are equivariant under rotations about the vertical
axis alone, and Mobula under the rotoreflection group S4. Trinacria is
equivariant under the chiral dihedral group D3 of order 6 (Schoenflies),
generated by

    rho:   (w, z) -> (e^{2 pi i/3} w, z)     rotation by 120 degrees about z
    kappa: (w, z) -> (conj(w), -z)            half-turn about the x axis,
                                              (x, y, z) -> (x, -y, -z)

with w = x + i*y. The six elements are {1, rho, rho^2, kappa, rho*kappa,
rho^2*kappa}: three rotations about z and three half-turns about horizontal
axes at angles 0, 60 and 120 degrees (equivalently 0 and +-120 degrees, since a
half-turn axis is a line). All six have determinant +1, so the group is chiral:
the attractor has no mirror symmetry of any kind.

kappa forbids a uniform spin. A constant rotation rate i*omega0*w is not
kappa-equivariant, so the only admissible rotation rate is odd in z: the
linear spin omega*z has opposite signs above and below the mid-plane, and
kappa exchanges the two halves. On the attractor this shows as a
counter-rotating core: within radius 0.6 of the axis (about 55 percent of the
time) the upper half winds counterclockwise (mean angular velocity +0.59 for
r < 0.1, +0.47 for 0.1 < r < 0.3, +0.29 for 0.3 < r < 0.6) and the lower
half clockwise by the same amounts, while the outer parts of each half turn
weakly the other way (-0.03 and -0.07 above the plane for r > 0.6). The
time-averaged angular momentum Lz of each half is therefore close to zero
(+0.002 and -0.005); the counter-rotation is a property of the core, not of
the half as a whole (64-orbit ensemble, results/trinacria_verification.json,
single_attractor_test.ensemble.radius_bands).

Trinacria Heiberg 1863 is an extinct marine diatom genus (Paleocene-Eocene
fossils from Denmark) named for the
triskelion of Sicily: three legs turning one way, reversed when the disc is
turned over. That reversal is what kappa does to this flow's two halves, and a
diatom frustule is itself two valves stacked top and bottom.

Complex form: the n = 3 member of the D_n family atlas/family_d.py, whose
equivariance under every group element is proven in
tests/test_d_equivariance.py:

    dw/dt = (alpha*z^2 - beta + i*omega*z) w
            + gamma*conj(w)^2 + i*delta*z*conj(w)^2
    dz/dt = nu*z - z^3 - lam*z*|w|^2 + eps*Im(w^3)

Derivation of the real form. With w = x + i*y:

    i*omega*z*w         = -omega*z*y            + i*omega*z*x
    conj(w)^2           = (x^2 - y^2)           - i*2xy
    gamma*conj(w)^2     = gamma*(x^2 - y^2)     - i*2*gamma*xy
    i*delta*z*conj(w)^2 = 2*delta*z*xy          + i*delta*z*(x^2 - y^2)
    |w|^2               = x^2 + y^2
    Im(w^3)             = 3x^2 y - y^3

so, collecting real and imaginary parts (c = alpha*z^2 - beta):

    dx/dt = c x - omega z y + gamma (x^2 - y^2) + 2 delta z x y
    dy/dt = c y + omega z x - 2 gamma x y + delta z (x^2 - y^2)
    dz/dt = nu z - z^3 - lam z (x^2 + y^2) + eps (3 x^2 y - y^3)

The omega, gamma and delta terms are the D3-not-D3h and D3-not-D3d
signatures: omega = delta = eps = 0 would restore the z-flip and the vertical
mirrors (D3h), omega = gamma = 0 would restore the rotoreflection S6 and the
diagonal mirrors (D3d, which contains the inversion -I), and
gamma = delta = eps = 0 would restore rotation by every angle.

Divergence. The omega term is a z-dependent rotation and the gamma and delta
terms are anti-holomorphic in w, so all three are trace-free; Im(w^3) does not
depend on z. Hence

    div F = 2 (alpha z^2 - beta) + nu - 3 z^2 - lam (x^2 + y^2),

the same closed form as Mobula.

Equilibrium skeleton (see equilibria.py). On the axis the planar equations
vanish and dz/dt = z (nu - z^2), giving the origin and the kappa-conjugate
pair (0, 0, +-sqrt(nu)). At z = 0 the rotation rate omega*z vanishes, so the
planar linear part at the origin is -beta * Identity: the origin is a saddle
with a DOUBLE real eigenvalue -beta and the eigenvalue nu along z, not a
saddle-focus as in the C_n specimens. The on-axis pair have identical spectra
and opposite rotation sense: J_xy - J_yx = -2 omega z changes sign with z.

Canonical parameters (nominee #8 of results/d3_candidates.json, frozen at the
4-decimal probe values, no polishing; selection record in
results/d3_selection.json):

    alpha = 1.4773, beta = 1.4668, omega = 0.7168, gamma = 0.8446,
    delta = 1.0567, nu = 2.3978, lam = 1.2975, eps = -1.5491.

beta sits at 1.4668 against the search-box face 1.5; this has no bearing on
the specimen because the values were selected, not optimized.

Basin disclosure. The attractor coexists with escape to infinity. On the
basin protocol shared with the other specimens (scripts/basin_comparison.py:
48 ICs uniform in [-2, 2]^3, rng seed 0) 24 stay bounded and all 24 land on
the symmetric chaotic set; a 480-IC draw gives a bounded fraction of
0.56 +- 0.02, every bounded orbit landing (the selection stage's own draw gave
29/48, results/d3_selection.json). For comparison: Aurelia 48/48, Naiad 48/48,
Cassiopea 43/48, Mobula 41/48. Start from DEFAULT_STATE or from points within
about 0.1 of the attractor: a few points 0.3 away already lie outside the
basin and escape at once (scripts/verify_trinacria.py, B9b).
"""

from __future__ import annotations

import numpy as np

# Canonical parameters of the Trinacria attractor.
ALPHA, BETA, OMEGA, GAMMA, DELTA, NU, LAM, EPS = (
    1.4773, 1.4668, 0.7168, 0.8446, 1.0567, 2.3978, 1.2975, -1.5491,
)

DEFAULT_STATE = (0.3, 0.2, 0.1)


def group_matrices():
    """The six elements of D3 as real 3x3 matrices acting on (x, y, z).

    Order: identity, rho, rho^2, kappa, rho*kappa, rho^2*kappa, where rho is
    the 120-degree rotation about z and kappa = diag(1, -1, -1). The products
    rho^k*kappa are half-turns about the horizontal axes at angles k*60 degrees.
    """
    c, s = np.cos(2 * np.pi / 3), np.sin(2 * np.pi / 3)
    r = np.array([[c, -s, 0.0], [s, c, 0.0], [0.0, 0.0, 1.0]])
    k = np.diag([1.0, -1.0, -1.0])
    r2 = r @ r
    return [np.eye(3), r, r2, k, r @ k, r2 @ k]


def velocity(state, alpha=ALPHA, beta=BETA, omega=OMEGA, gamma=GAMMA,
             delta=DELTA, nu=NU, lam=LAM, eps=EPS):
    """Right-hand side of the Trinacria system at ``state = (x, y, z)``."""
    x, y, z = state
    c = alpha * z * z - beta
    d2 = x * x - y * y
    return np.array(
        [
            c * x - omega * z * y + gamma * d2 + 2 * delta * z * x * y,
            c * y + omega * z * x - 2 * gamma * x * y + delta * z * d2,
            nu * z - z**3 - lam * z * (x * x + y * y) + eps * (3 * x * x * y - y**3),
        ]
    )


def jacobian(state, alpha=ALPHA, beta=BETA, omega=OMEGA, gamma=GAMMA,
             delta=DELTA, nu=NU, lam=LAM, eps=EPS):
    """Jacobian matrix of the flow at ``state = (x, y, z)`` (hand-derived)."""
    x, y, z = state
    c = alpha * z * z - beta
    d2 = x * x - y * y
    return np.array(
        [
            [c + 2 * gamma * x + 2 * delta * z * y,
             -omega * z - 2 * gamma * y + 2 * delta * z * x,
             2 * alpha * z * x - omega * y + 2 * delta * x * y],
            [omega * z - 2 * gamma * y + 2 * delta * z * x,
             c - 2 * gamma * x - 2 * delta * z * y,
             2 * alpha * z * y + omega * x + delta * d2],
            [-2 * lam * z * x + 6 * eps * x * y,
             -2 * lam * z * y + 3 * eps * d2,
             nu - 3 * z * z - lam * (x * x + y * y)],
        ]
    )


def divergence(state, alpha=ALPHA, beta=BETA, omega=OMEGA, gamma=GAMMA,
               delta=DELTA, nu=NU, lam=LAM, eps=EPS):
    """Trace of the Jacobian. The omega, gamma and delta terms are trace-free."""
    x, y, z = state
    return 2 * (alpha * z * z - beta) + nu - 3 * z * z - lam * (x * x + y * y)


def rk4_step(state, dt, alpha=ALPHA, beta=BETA, omega=OMEGA, gamma=GAMMA,
             delta=DELTA, nu=NU, lam=LAM, eps=EPS):
    """One classical fourth-order Runge-Kutta step."""
    p = (alpha, beta, omega, gamma, delta, nu, lam, eps)
    k1 = velocity(state, *p)
    k2 = velocity(state + 0.5 * dt * k1, *p)
    k3 = velocity(state + 0.5 * dt * k2, *p)
    k4 = velocity(state + dt * k3, *p)
    return state + (dt / 6.0) * (k1 + 2 * k2 + 2 * k3 + k4)


def trajectory(n_steps=500_000, dt=0.004, transient=40_000, state0=DEFAULT_STATE,
               alpha=ALPHA, beta=BETA, omega=OMEGA, gamma=GAMMA,
               delta=DELTA, nu=NU, lam=LAM, eps=EPS):
    """Integrate the flow and return an ``(n_steps, 3)`` array on the attractor."""
    p = (alpha, beta, omega, gamma, delta, nu, lam, eps)
    s = np.asarray(state0, dtype=float)
    for _ in range(transient):
        s = rk4_step(s, dt, *p)
    pts = np.empty((n_steps, 3))
    for i in range(n_steps):
        s = rk4_step(s, dt, *p)
        pts[i] = s
    return pts
